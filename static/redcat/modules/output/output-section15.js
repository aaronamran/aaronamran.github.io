/** Red Cat - Section 15: Boot Process & Maintenance */

function generateSection15Output(command, input, tokens) {
    // systemctl get-default
    if (command === 'systemctl' && input.includes('get-default')) {
        if (input.includes('graphical')) {
            return 'graphical.target';
        }
        return 'multi-user.target';
    }

    // systemctl set-default
    if (command === 'systemctl' && input.includes('set-default')) {
        if (input.includes('graphical.target')) {
            return 'Removed /etc/systemd/system/default.target.\nCreated symlink /etc/systemd/system/default.target → /usr/lib/systemd/system/graphical.target.';
        }
        if (input.includes('multi-user.target')) {
            return 'Removed /etc/systemd/system/default.target.\nCreated symlink /etc/systemd/system/default.target → /usr/lib/systemd/system/multi-user.target.';
        }
        return null;
    }

    // systemctl isolate rescue.target
    if (command === 'systemctl' && input.includes('isolate') && input.includes('rescue.target')) {
        return null; // system transitions, no stdout
    }

    // systemctl isolate emergency.target
    if (command === 'systemctl' && input.includes('isolate') && input.includes('emergency.target')) {
        return null;
    }

    // systemctl isolate default.target
    if (command === 'systemctl' && input.includes('isolate') && input.includes('default.target')) {
        return null;
    }

    // systemctl list-units --type=target
    if (command === 'systemctl' && input.includes('list-units') && (input.includes('--type=target') || (input.includes('-t') && input.includes('target')))) {
        const stateFilter = input.includes('--state=active') || input.includes('active');
        const list = stateFilter
            ? 'UNIT                   LOAD   ACTIVE SUB    DESCRIPTION\nbasic.target           loaded active active Basic System\ncryptsetup.target      loaded active active Local Encrypted Volumes\nmulti-user.target      loaded active active Multi-User System\nnetwork.target         loaded active active Network\nremote-fs.target       loaded active active Remote File Systems\n\n5 loaded units listed.'
            : 'UNIT                   LOAD   ACTIVE SUB    DESCRIPTION\nbasic.target           loaded active active Basic System\ncryptsetup.target      loaded active active Local Encrypted Volumes\ngraphical.target       loaded inactive dead   Graphical Interface\nmulti-user.target      loaded active active Multi-User System\nnetwork.target         loaded active active Network\nrescue.target          loaded inactive dead   Rescue Mode\n\n6 loaded units listed.';
        return list;
    }

    // systemctl list-dependencies graphical.target
    if (command === 'systemctl' && input.includes('list-dependencies') && input.includes('graphical.target')) {
        return 'graphical.target\n● ├─accounts-daemon.service\n● ├─gdm.service\n● ├─rtkit-daemon.service\n● └─multi-user.target\n●   ├─crond.service\n●   ├─sshd.service\n●   └─network.target';
    }

    // ls -l /etc/systemd/system/default.target
    if (command === 'ls' && input.includes('-l') && input.includes('default.target')) {
        return 'lrwxrwxrwx. 1 root root 37 Apr  7 08:00 /etc/systemd/system/default.target -> /usr/lib/systemd/system/multi-user.target';
    }

    // readlink /etc/systemd/system/default.target
    if (command === 'readlink' && input.includes('default.target')) {
        return '/usr/lib/systemd/system/multi-user.target';
    }

    // cat /boot/grub2/grub.cfg
    if ((command === 'cat' || command === 'less') && input.includes('/boot/grub2/grub.cfg')) {
        return '#\n# DO NOT EDIT THIS FILE\n# It is automatically generated by grub2-mkconfig\n#\n# BEGIN /etc/grub.d/00_header\nset default="0"\nset timeout=5\n\nmenuentry \'Red Hat Enterprise Linux (5.14.0-284.11.1.el9_2.x86_64) 9.2 (Plow)\' {\n\tlinux   /vmlinuz-5.14.0-284.11.1.el9_2.x86_64 root=/dev/mapper/rhel-root ro crashkernel=1G-4G:192M,4G-64G:256M,64G-:512M resume=/dev/mapper/rhel-swap rd.lvm.lv=rhel/root rd.lvm.lv=rhel/swap rhgb quiet\n\tinitrd  /initramfs-5.14.0-284.11.1.el9_2.x86_64.img\n}';
    }

    // cat /etc/default/grub
    if ((command === 'cat' || command === 'grep') && input.includes('/etc/default/grub')) {
        if (command === 'grep' && input.includes('GRUB_TIMEOUT')) {
            return 'GRUB_TIMEOUT=5';
        }
        return 'GRUB_TIMEOUT=5\nGRUB_DISTRIBUTOR="$(sed \'s, release .*$,,g\' /etc/system-release)"\nGRUB_DEFAULT=saved\nGRUB_DISABLE_SUBMENU=true\nGRUB_TERMINAL_OUTPUT="console"\nGRUB_CMDLINE_LINUX="crashkernel=1G-4G:192M,4G-64G:256M,64G-:512M resume=/dev/mapper/rhel-swap rd.lvm.lv=rhel/root rd.lvm.lv=rhel/swap rhgb quiet"\nGRUB_DISABLE_RECOVERY="true"\nGRUB_ENABLE_BLSCFG=true';
    }

    // grub2-mkconfig -o /boot/grub2/grub.cfg
    if (command === 'grub2-mkconfig' && input.includes('-o') && input.includes('/boot/grub2/grub.cfg')) {
        return 'Generating grub configuration file ...\nAdding boot menu entry for UEFI Firmware Settings ...\ndone';
    }

    // grub2-editenv list
    if (command === 'grub2-editenv' && input.includes('list')) {
        return 'saved_entry=0\nkernel_cmdline=ro';
    }

    // grub2-set-default
    if (command === 'grub2-set-default') {
        return null;
    }

    // uname -r : kernel version
    if (command === 'uname' && input.includes('-r')) {
        return '5.14.0-284.11.1.el9_2.x86_64';
    }

    // uname -a : all kernel info
    if (command === 'uname' && input.includes('-a')) {
        return 'Linux localhost.localdomain 5.14.0-284.11.1.el9_2.x86_64 #1 SMP PREEMPT_DYNAMIC Thu Apr 20 17:11:28 EDT 2023 x86_64 x86_64 x86_64 GNU/Linux';
    }

    // ls /boot : list boot directory
    if (command === 'ls' && (input === '/boot' || input.endsWith(' /boot') || input.includes('/boot '))) {
        if (input.includes('-l')) {
            return 'total 185372\n-rw-r--r--. 1 root root   227499 Apr 20  2023 config-5.14.0-284.11.1.el9_2.x86_64\ndrwxr-xr-x. 3 root root     4096 Apr  7 08:00 efi\ndrwx------. 4 root root     4096 Apr  7 08:00 grub2\n-rw-------. 1 root root 85451959 Apr 20  2023 initramfs-5.14.0-284.11.1.el9_2.x86_64.img\n-rwxr-xr-x. 1 root root 10698792 Apr 20  2023 vmlinuz-5.14.0-284.11.1.el9_2.x86_64';
        }
        return 'config-5.14.0-284.11.1.el9_2.x86_64  efi  grub2  initramfs-5.14.0-284.11.1.el9_2.x86_64.img  vmlinuz-5.14.0-284.11.1.el9_2.x86_64';
    }

    // lsmod : kernel modules
    if (command === 'lsmod') {
        return 'Module                  Size  Used by\nnft_fib_inet           16384  1\nnft_fib_ipv4           16384  1 nft_fib_inet\nnft_fib_ipv6           16384  1 nft_fib_inet\nnft_fib                16384  3 nft_fib_ipv6,nft_fib_ipv4,nft_fib_inet\nvfat                   24576  1\nfat                    86016  1 vfat\nxhci_pci               24576  0\nxhci_hcd              331776  1 xhci_pci';
    }

    // modinfo <module>
    if (command === 'modinfo') {
        const modName = tokens[1] || 'vfat';
        return `filename:       /lib/modules/5.14.0-284.11.1.el9_2.x86_64/kernel/fs/${modName}/${modName}.ko.xz\ndescription:    VFAT fs support\nauthor:         Gordon Chaffee\nlicense:        GPL\nalias:          fs-vfat\ndepends:        fat\nretpoline:      Y\nrhelversion:    9.2`;
    }

    // dracut: regenerate initramfs
    if (command === 'dracut' && input.includes('-f')) {
        return null; // runs silently
    }

    return null;
}

function generateSection15PreCheck(task, command, input, tokens) {
    // before set-default — show current default
    if (command === 'systemctl' && input.includes('get-default')) {
        return 'graphical.target';
    }

    // before grub2-mkconfig — show current timeout
    if (command === 'grep' && input.includes('GRUB_TIMEOUT')) {
        return 'GRUB_TIMEOUT=5';
    }

    // before listing targets
    if (command === 'systemctl' && input.includes('list-units') && input.includes('target')) {
        return 'multi-user.target loaded active active Multi-User System\ngraphical.target  loaded inactive dead   Graphical Interface';
    }


    // Added for the free-terminal/practice parity: boot, journal and login history output
    if (command === 'grubby' && input.includes('--info')) {
        return 'index=0\nkernel="/boot/vmlinuz-5.14.0-362.8.1.el9_3.x86_64"\nargs="ro crashkernel=1G-4G:192M resume=/dev/mapper/rhel-swap rd.lvm.lv=rhel/root rd.lvm.lv=rhel/swap rhgb quiet"\nroot="/dev/mapper/rhel-root"\ninitrd="/boot/initramfs-5.14.0-362.8.1.el9_3.x86_64.img"\ntitle="Red Hat Enterprise Linux (5.14.0-362.8.1.el9_3.x86_64) 9.3 (Plow)"\nid="4a9d1c2e7b5f4e0f9a3c6d1e8b2f7a90-5.14.0-362.8.1.el9_3.x86_64"';
    }
    if (command === 'ls' && input.includes('/boot/loader/entries')) {
        return '4a9d1c2e7b5f4e0f9a3c6d1e8b2f7a90-0-rescue.conf\n4a9d1c2e7b5f4e0f9a3c6d1e8b2f7a90-5.14.0-284.11.1.el9_2.x86_64.conf\n4a9d1c2e7b5f4e0f9a3c6d1e8b2f7a90-5.14.0-362.8.1.el9_3.x86_64.conf';
    }
    if (command === 'last' && input.includes('reboot')) {
        return 'reboot   system boot  5.14.0-362.8.1.e Mon Nov  2 09:00   still running\nreboot   system boot  5.14.0-362.8.1.e Fri Oct 30 08:12 - 17:45  (3+09:33)\nreboot   system boot  5.14.0-284.11.1.e Tue Oct 20 10:03 - 08:11 (9+22:08)\n\nwtmp begins Tue Oct 20 10:03:41 2026';
    }
    if (command === 'journalctl' && input.includes('--disk-usage')) {
        return 'Archived and active journals take up 96.0M in the file system.';
    }
    if (command === 'journalctl' && (input.includes('-b -1') || input.includes('--boot=-1'))) {
        return '-- Boot 0f3c2a9d8b7e4c61a5d2e9f1b3c4d5e6 --\nOct 30 08:12:03 rhcsa-lab kernel: Linux version 5.14.0-362.8.1.el9_3.x86_64\nOct 30 08:12:09 rhcsa-lab systemd[1]: Started OpenSSH server daemon.\nOct 30 17:45:01 rhcsa-lab systemd[1]: Reached target Shutdown.';
    }
    if (command === 'journalctl' && input.includes('-p')) {
        return 'Nov 02 09:00:07 rhcsa-lab kernel: ACPI BIOS Error (bug): Could not resolve symbol [\\_SB.PCI0], AE_NOT_FOUND\nNov 02 09:00:12 rhcsa-lab systemd[1]: Failed to start Network Manager Wait Online.';
    }
    if (command === 'systemctl' && input.includes('kdump')) {
        return '● kdump.service - Crash recovery kernel arming\n     Loaded: loaded (/usr/lib/systemd/system/kdump.service; enabled; preset: enabled)\n     Active: active (exited) since Mon 2026-11-02 09:00:15 UTC; 4h ago\n   Main PID: 842 (code=exited, status=0/SUCCESS)';
    }
    if (command === 'who') {
        return input.includes('-b') ? '         system boot  2026-11-02 09:00' : '         run-level 3  2026-11-02 09:00';
    }

    return null;
}
